#!/usr/bin/env python3
"""Re-packs the readable level data into VLQP_AB/level.h.

Edit level_data_readable.h (survivor / player+exit positions and the 8x8-tile
blocks), then run:  python3 pack_level_data.py
Every value is < 64 so it is stored in 6 bits (4 values = 3 bytes).
The packed arrays in level.h between the BEGIN/END PACKED markers are replaced.
"""
import re, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'level_data_readable.h')).read()
dst_path = os.path.join(here, '..', 'VLQP_AB', 'level.h')

def values(name):
    m = re.search(name + r'[^=]*=\s*\{(.*?)\n\};', src, re.S)
    body = re.sub(r'//.*', '', m.group(1))
    return [int(x) for x in re.findall(r'\d+', body)]

def pack6(vals):
    assert all(0 <= v < 64 for v in vals)
    bits = 0; n = 0; out = []
    for v in vals:
        bits |= v << n; n += 6
        while n >= 8:
            out.append(bits & 255); bits >>= 8; n -= 8
    if n: out.append(bits & 255)
    out.append(0)  # read6() reads a word, so keep one spare byte
    return out

def fmt(name, vals, comment):
    p = pack6(vals)
    rows = ['  ' + ', '.join('0x%02X' % b for b in p[i:i+16]) for i in range(0, len(p), 16)]
    return '// %s (%d values, 6 bits each)\nPROGMEM const unsigned char %s[] = {\n%s\n};\n' % (
        comment, len(vals), name, ',\n'.join(rows))

block = '// BEGIN PACKED DATA (generated by tools/pack_level_data.py)\n'
block += fmt('survivorLocation', values('survivorLocation'), '10 values per map: x,y of 5 survivors')
block += '\n' + fmt('playerAndExitLocation', values('playerAndExitLocation'), '4 values per level: player x,y exit x,y')
block += '\n' + fmt('blocks', values('blocks'), '16 blocks of 8x8 tile types')
block += '// END PACKED DATA'
dst = open(dst_path).read()
dst = re.sub(r'// BEGIN PACKED DATA.*?// END PACKED DATA', lambda m: block, dst, flags=re.S)
open(dst_path, 'w').write(dst)
print('level.h updated')
